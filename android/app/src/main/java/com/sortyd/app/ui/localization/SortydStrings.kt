package com.sortyd.app.ui.localization

import java.util.Locale

object SortydStrings {
    fun languageName(code: String): String = when (code.normalizedLanguage()) {
        "zh-Hans" -> "Chinese"
        "ar" -> "Arabic"
        "es" -> "Spanish"
        else -> "English"
    }

    fun statusValues(code: String): String = when (code.normalizedLanguage()) {
        "zh-Hans" -> "强项、发展中、需改善"
        "ar" -> "قوي، قيد التطوير، متعثر"
        "es" -> "Fuerte, En desarrollo, Con dificultades"
        else -> "Strong, Developing, Struggling"
    }

    fun t(code: String, key: String): String {
        val lang = code.normalizedLanguage()
        return translations[lang]?.get(key) ?: translations["en"]?.get(key) ?: key
    }

    fun status(code: String, raw: String, score: Int): String {
        val cleaned = raw.trim()
        val normalized = cleaned.lowercase(Locale.ROOT).replace("_", " ").replace("-", " ")
        return when (normalized) {
            "strong", "strength", "healthy", "good", "excellent", "fuerte", "قوي", "强项" -> t(code, "Strong")
            "developing", "building", "improving", "moderate", "need work", "needs work", "average", "on track",
            "en desarrollo", "قيد التطوير", "发展中" -> t(code, "Developing")
            "struggling", "strugglong", "strugling", "struggle", "weak", "critical", "low", "poor",
            "con dificultades", "متعثر", "需改善", "挣扎中" -> t(code, "Struggling")
            else -> {
                if (langNeedsProtection(code) && normalized.any { it in 'a'..'z' }) scoreBasedStatus(code, score)
                else cleaned.ifBlank { scoreBasedStatus(code, score) }
            }
        }
    }

    fun scoreBasedStatus(code: String, score: Int): String = when {
        score >= 75 -> t(code, "Strong")
        score >= 45 -> t(code, "Developing")
        else -> t(code, "Struggling")
    }

    private fun langNeedsProtection(code: String): Boolean = code.normalizedLanguage() != "en"

    private fun String.normalizedLanguage(): String = when {
        startsWith("zh", ignoreCase = true) -> "zh-Hans"
        startsWith("ar", ignoreCase = true) -> "ar"
        startsWith("es", ignoreCase = true) -> "es"
        else -> "en"
    }

